<?php
/**
 * TemplateDefaults — Default feed configuration per merchant template.
 *
 * V8 equivalent of V5's TemplateConfig.
 * Provides the default attribute mappings, types, prefixes, suffixes,
 * output types, and limits that pre-populate the feed editor when a
 * user selects a merchant template.
 *
 * Each merchant key maps to an array with parallel arrays:
 *   - mattributes : merchant attribute keys
 *   - prefix      : prefix per attribute
 *   - type        : 'attribute' or 'pattern'
 *   - attributes  : WC attribute to map to (empty for patterns)
 *   - default     : default/static value (used when type=pattern)
 *   - suffix      : suffix per attribute
 *   - output_type : output type code per attribute
 *   - limit       : character limit per attribute
 *
 * Usage:
 *   TemplateDefaults::get( 'google' )               → config for Google
 *   TemplateDefaults::get_multiple( ['google','fb'] ) → batch configs
 *
 * @package    CTXFeed
 * @subpackage V8/Channel
 * @since      8.0.0
 * @implements CHAN-FRD-4.1
 */

