	 * Cached brand name.
	 *
	 * @since 8.0.0
	 * @var string
	 */
	private static $brand;

	/**
	 * Cached currency code.
	 *
	 * @since 8.0.0
	 * @var string
	 */
	private static $currency;

	/**
	 * Constructor — initialize brand and currency.
	 *
	 * @since 8.0.0
	 *
	 * @param string|null $currency WooCommerce currency code.
	 * @param string|null $brand    Brand name override.
	 */
	public function __construct( $currency = null, $brand = null ) {
		self::$brand    = ! empty( $brand ) ? $brand : self::default_brand();
		self::$currency = ! empty( $currency ) ? $currency : get_woocommerce_currency();
	}

	/**
	 * Guess brand name from site URL.
	 *
	 * Extracts the second-level domain from the site URL and capitalizes it.
	 * E.g., https://shop.example.com → 'Example'.
	 *
	 * @since 8.0.0
	 *
	 * @return string Brand name.
	 */
	public static function default_brand(): string {
		/**
		 * Pre-filter brand name. Return non-null to short-circuit.
		 *
		 * @since 5.0.0 (V5 legacy)
		 * @since 8.0.0
		 *
		 * @param string|null $brand Brand name or null to auto-detect.
		 */
		$brand = apply_filters( 'woo_feed_pre_get_default_brand_name', null );

		if ( ! is_null( $brand ) ) {
			return $brand;
		}

		if ( ! empty( self::$brand ) ) {
			return self::$brand;
		}

		$brand = '';
		$url   = filter_var( site_url(), FILTER_SANITIZE_URL );

		if ( false !== $url ) {
			$url = wp_parse_url( $url );

			if ( array_key_exists( 'host', $url ) ) {
				if ( strpos( $url['host'], '.' ) !== false ) {
					$arr   = explode( '.', $url['host'] );
					$brand = $arr[ count( $arr ) - 2 ];
					$brand = ucfirst( $brand );
				} else {
					$brand = ucfirst( $url['host'] );
				}
			}
		}

		self::$brand = $brand;

		/**
		 * Filter the auto-detected brand name.
		 *
		 * @since 5.0.0 (V5 legacy)
		 * @since 8.0.0
		 *
		 * @param string $brand Auto-detected brand name.
		 */
		return apply_filters( 'woo_feed_get_default_brand_name', $brand );
	}

	/**
	 * Get WooCommerce currency code (cached).
	 *
	 * @since 8.0.0
	 *
	 * @return string Currency code (e.g., 'USD').
	 */
	public static function get_currency(): string {
		if ( ! empty( self::$currency ) ) {
			return self::$currency;
		}

		self::$currency = get_woocommerce_currency();

		return self::$currency;
	}

	/**
	 * Get default feed configuration for a merchant template.
	 *
	 * @since 8.0.0
	 *
	 * @param string      $merchant Merchant/template key (e.g., 'google', 'facebook', 'custom').
	 * @param string|null $currency Optional currency override.
	 * @param string|null $brand    Optional brand override.
	 * @return array Template configuration with parallel arrays.
	 */
	public static function get( $merchant = 'custom', $currency = null, $brand = null ): array {
		self::$brand    = ! empty( $brand ) ? $brand : self::default_brand();
		self::$currency = ! empty( $currency ) ? $currency : self::get_currency();

		$config = self::data();

		// V5-compat overlay for the Custom Template 2 (XML) merchant family.
		// V5 stored the per-merchant template string at
		// `wp_options['woo_feed_settings']['feed_config_custom2']` only after
		// the user saved a feed; for the FIRST visit to the Make Feed editor
		// V5 read the merchant's template file from disk
		// (V5/Merchant/TemplateConfig.php:10588-10601). Replicate the same
		// disk-load default so the React UI has a starting template to show
		// in its editor textarea. PROD-FRD-10.6.
		$custom2_default = self::custom2_default_template( (string) $merchant );
		if ( '' !== $custom2_default ) {
			$existing                        = isset( $config[ $merchant ] ) && is_array( $config[ $merchant ] )
				? $config[ $merchant ]
				: array();
			$existing['feed_config_custom2'] = $custom2_default;
			return $existing;
		}

		if ( isset( $config[ $merchant ] ) ) {
			return $config[ $merchant ];
		}

		// V5 parity: a few channels reuse the Google attribute template wholesale
		// (V5 TemplateConfig::get mapped e.g. 'pinterest' → 'google'). Without this
		// alias a fresh Pinterest Catalog feed fell back to the generic 'default'
		// rows, which OMIT availability and item_group_id and name the image /
		// category columns 'image_link' / 'categories' — names the Pinterest
		// attribute-name mapper does NOT remap, so Pinterest silently dropped
		// them. Aliasing to 'google' restores availability (→ g:availability,
		// BUG-0040), item_group_id (→ g:item_group_id for variations, BUG-0042)
		// and image / product_type (→ g:image_link / g:product_type, BUG-0041).
		// Only 'pinterest' — 'pinterest_rss' is a separate provider with its own
		// template entry.
		$template_aliases = array(
			'pinterest' => 'google',
		);
		if ( isset( $template_aliases[ $merchant ], $config[ $template_aliases[ $merchant ] ] ) ) {
			return $config[ $template_aliases[ $merchant ] ];
		}

		// Fall back to default template config.
		return $config['default'] ?? array();
	}

	/**
	 * Return the on-disk default template body for a Custom Template 2 (XML)
	 * merchant, or '' when the merchant doesn't use this family.
	 *
	 * Reads the same files V5 read from
	 * `admin/partials/templates/custom2/{merchant}.txt`. Result is cached
	 * per-request so multiple `get()` calls in the same request don't hit
	 * the filesystem repeatedly.
	 *
	 * @since 8.0.0
	 *
	 * @param string $merchant Merchant key.
	 * @return string Template body or empty string.
	 */
	private static function custom2_default_template( string $merchant ): string {
		// V5 wires four merchants with disk-default templates.
		$known = array( 'custom2', 'admarkt', 'glami', 'yandex_xml' );
		if ( ! in_array( $merchant, $known, true ) ) {
			return '';
		}

		static $cache = array();
		if ( isset( $cache[ $merchant ] ) ) {
			return $cache[ $merchant ];
		}

		$file = TemplateLocator::path( 'custom2/' . $merchant . '.txt' );
		if ( '' === $file || ! file_exists( $file ) ) {
			$cache[ $merchant ] = '';
			return '';
		}

		// phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents, WordPressVIPMinimum.Performance.FetchingRemoteData.FileGetContentsUnknown -- Local read only: $file is resolved by TemplateLocator to a .txt template shipped inside this plugin, whitelisted against the four merchant names above. No remote fetch is possible, and the result is memoised in the static $cache.
		$contents           = file_get_contents( $file );
		$cache[ $merchant ] = is_string( $contents ) ? $contents : '';

		return $cache[ $merchant ];
	}

	/**
	 * Batch fetch configs for multiple merchants.
	 *
	 * @since 8.0.0
	 *
	 * @param string[] $merchants Array of merchant/template keys.
	 * @return array Associative array of merchant_key => config.
	 */
	public static function get_multiple( array $merchants = array() ): array {
		if ( empty( $merchants ) ) {
			return array();
		}

		$result = array();

		foreach ( $merchants as $merchant ) {
			$result[ $merchant ] = self::get( $merchant );
		}

		return $result;
	}

